import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { Share2, Copy, Check, ExternalLink, X, Sparkles, Globe, Lock } from 'lucide-react';
import api from '../services/api';

export default function ShareReportModal({ isOpen, onClose, currentDataset, briefingText }) {
  const [loading, setLoading] = useState(false);
  const [shareUrl, setShareUrl] = useState(null);
  const [copied, setCopied] = useState(false);
  const [reportTitle, setReportTitle] = useState('DataGem E-Commerce Settlement & Fee Audit');

  if (!isOpen) return null;

  const handleCreateShareLink = async () => {
    setLoading(true);
    try {
      const summaryMarkdown = briefingText || (
        `### 💎 DataGem Executive Audit Summary\n\n` +
        `**Generated:** ${new Date().toLocaleDateString()}\n` +
        `**Status:** Verified via Zero-Token In-Memory DuckDB OLAP Engine\n\n` +
        `#### Key Unit Economics:\n` +
        `- Evaluated Dataset Records: ${currentDataset ? currentDataset.length : 0} orders\n` +
        `- Forensic Status: Automated Volumetric Weight & Settlement Reconciliation Complete\n\n` +
        `> This audit was autonomously generated by DataGem. View complete SKU breakdowns, hidden bleeders, and recovery claims on [DataGem](https://www.datagem.app).`
      );

      const res = await api.post('/enterprise/reports/share', {
        title: reportTitle,
        summary_markdown: summaryMarkdown,
        chart_json: null
      });

      if (res.data?.share_token) {
        // Construct URL based on current host or production domain
        const origin = window.location.origin;
        const link = `${origin}/shared/${res.data.share_token}`;
        setShareUrl(link);
      }
    } catch (e) {
      console.error('Failed to generate share link:', e);
      alert('Unable to generate share link. Please verify your connection.');
    } finally {
      setLoading(false);
    }
  };

  const handleCopy = () => {
    if (!shareUrl) return;
    navigator.clipboard.writeText(shareUrl);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-[80] flex items-center justify-center p-4">
        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
          exit={{ opacity: 0 }}
          onClick={onClose}
          className="absolute inset-0 bg-black/75 backdrop-blur-md"
        />

        <motion.div
          initial={{ scale: 0.94, opacity: 0, y: 15 }}
          animate={{ scale: 1, opacity: 1, y: 0 }}
          exit={{ scale: 0.94, opacity: 0, y: 15 }}
          className="relative w-full max-w-lg bg-white dark:bg-[#090D14] border border-slate-200 dark:border-slate-800 rounded-3xl shadow-2xl p-6 sm:p-8 text-slate-900 dark:text-slate-100 overflow-hidden font-sans"
        >
          {/* Header */}
          <div className="flex items-center justify-between pb-4 border-b border-slate-200 dark:border-slate-800">
            <div className="flex items-center gap-3">
              <div className="w-10 h-10 rounded-2xl bg-sky-500/10 text-sky-500 flex items-center justify-center border border-sky-500/20">
                <Share2 className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-xl font-bold text-slate-900 dark:text-white">Shareable Audit Report</h3>
                <p className="text-xs text-slate-500 dark:text-slate-400">Generate a secure, read-only link for partners or investors.</p>
              </div>
            </div>
            <button
              onClick={onClose}
              aria-label="Close"
              className="p-2 rounded-xl text-slate-400 hover:text-slate-900 dark:hover:text-white hover:bg-slate-100 dark:hover:bg-slate-800 transition-colors"
            >
              <X className="w-5 h-5" />
            </button>
          </div>

          {/* Form Body */}
          <div className="py-6 space-y-4">
            <div>
              <label className="text-xs font-bold text-slate-700 dark:text-slate-300 block mb-1">
                Report Title
              </label>
              <input
                type="text"
                value={reportTitle}
                onChange={(e) => setReportTitle(e.target.value)}
                className="w-full px-3.5 py-2.5 bg-slate-50 dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl text-xs font-sans text-slate-900 dark:text-white focus:outline-none focus:ring-2 focus:ring-sky-500"
              />
            </div>

            <div className="p-4 rounded-xl bg-slate-50 dark:bg-[#05070A] border border-slate-200 dark:border-slate-800/80 space-y-2 text-xs">
              <div className="flex items-center justify-between font-mono text-[11px] text-slate-500">
                <span>RECORDS AUDITED</span>
                <span className="font-bold text-slate-900 dark:text-white">{currentDataset ? currentDataset.length : 0} orders</span>
              </div>
              <div className="flex items-center justify-between font-mono text-[11px] text-slate-500">
                <span>SECURITY ENCRYPTION</span>
                <span className="text-emerald-500 font-semibold">Zero-Trust Read-Only Token</span>
              </div>
              <div className="flex items-center justify-between font-mono text-[11px] text-slate-500">
                <span>VIRAL CALL TO ACTION</span>
                <span className="text-sky-400 font-semibold">Branded Seller Acquisition CTA</span>
              </div>
            </div>

            {shareUrl ? (
              <div className="space-y-3 pt-2">
                <label className="text-xs font-bold text-emerald-500 block">
                  ✓ Public Shareable Link Ready:
                </label>
                <div className="flex items-center gap-2">
                  <input
                    type="text"
                    readOnly
                    value={shareUrl}
                    className="flex-1 px-3.5 py-2.5 bg-slate-100 dark:bg-slate-900 border border-emerald-500/40 rounded-xl text-xs font-mono text-slate-900 dark:text-white focus:outline-none"
                  />
                  <button
                    onClick={handleCopy}
                    className="px-4 py-2.5 bg-emerald-500 hover:bg-emerald-400 text-black font-bold text-xs rounded-xl flex items-center gap-1.5 transition-all shrink-0"
                  >
                    {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
                    <span>{copied ? 'Copied!' : 'Copy Link'}</span>
                  </button>
                </div>
                <div className="flex justify-end">
                  <a
                    href={shareUrl}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="text-xs text-sky-500 hover:underline inline-flex items-center gap-1 font-mono"
                  >
                    <span>Preview Link in New Tab</span>
                    <ExternalLink className="w-3.5 h-3.5" />
                  </a>
                </div>
              </div>
            ) : (
              <button
                type="button"
                onClick={handleCreateShareLink}
                disabled={loading}
                className="w-full py-3.5 rounded-xl font-bold text-xs text-white bg-gradient-to-r from-sky-500 to-emerald-500 hover:opacity-95 transition-opacity flex items-center justify-center gap-2 shadow-lg shadow-sky-500/20 disabled:opacity-50"
              >
                {loading ? (
                  <span>Generating Secure Token...</span>
                ) : (
                  <>
                    <Globe className="w-4 h-4" />
                    <span>Generate Shareable Report Link</span>
                  </>
                )}
              </button>
            )}
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
}
