import React, { useState, useEffect } from 'react';
import { useParams, Link } from 'react-router-dom';
import { motion } from 'framer-motion';
import api from '../services/api';

export default function SharedReportView() {
  const { token } = useParams();
  const [report, setReport] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  useEffect(() => {
    api.get(`/enterprise/reports/shared/${token}`)
      .then(res => setReport(res.data))
      .catch(err => setError(err.response?.data?.detail || "Report not found or expired"))
      .finally(() => setLoading(false));
  }, [token]);

  if (loading) {
    return (
      <div className="min-h-screen bg-[#070A10] flex items-center justify-center text-slate-400 font-mono text-sm">
        Loading verified DataGem report...
      </div>
    );
  }

  if (error || !report) {
    return (
      <div className="min-h-screen bg-[#070A10] flex flex-col items-center justify-center p-6 text-center">
        <div className="text-4xl mb-4">🔒</div>
        <h2 className="text-xl font-bold text-white mb-2">Report Not Accessible</h2>
        <p className="text-sm text-slate-400 max-w-md mb-6">{error || "This link may have been revoked or expired."}</p>
        <Link to="/" className="px-5 py-2.5 bg-sky-600 hover:bg-sky-500 text-white rounded-xl text-xs font-semibold">
          Return to DataGem Home
        </Link>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-[#070A10] text-slate-100 font-sans p-6 sm:p-12 relative">
      <div className="max-w-4xl mx-auto bg-[#0C121E] border border-slate-800 rounded-3xl p-8 shadow-2xl">
        {/* Header */}
        <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center pb-6 border-b border-slate-800 gap-4">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-sky-500 to-emerald-500 flex items-center justify-center text-slate-950 font-extrabold text-sm shadow-md font-mono">
              DG
            </div>
            <div>
              <h1 className="text-2xl font-bold text-white tracking-tight">{report.title}</h1>
              <div className="flex items-center gap-2 text-xs font-mono text-slate-500 mt-1">
                <span>Verified Snapshot</span> • 
                <span>{report.views} Views</span> • 
                <span>{new Date(report.created_at).toLocaleDateString()}</span>
              </div>
            </div>
          </div>

          <div className="px-3 py-1 bg-emerald-950/60 border border-emerald-800 text-emerald-400 text-xs font-mono rounded-full flex items-center gap-1.5">
            <span className="w-2 h-2 rounded-full bg-emerald-500 animate-pulse" />
            LIVE READ-ONLY
          </div>
        </div>

        {/* Content Body */}
        <div className="py-8 prose prose-invert max-w-none">
          <div className="whitespace-pre-wrap font-sans text-slate-300 text-sm leading-relaxed bg-[#080D15] p-6 rounded-2xl border border-slate-800/80">
            {report.summary}
          </div>
        </div>

        {/* Footer */}
        <div className="pt-6 border-t border-slate-800 flex flex-col sm:flex-row items-center justify-between text-xs font-mono text-slate-500 gap-4">
          <span>Generated by DataGem In-Memory Analytics Engine</span>
          <Link to="/" className="text-sky-400 hover:text-sky-300 font-semibold">
            Deploy DataGem for your store →
          </Link>
        </div>
      </div>
    </div>
  );
}
